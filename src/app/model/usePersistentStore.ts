import { useEffect,useState } from "react";
import { initialStore } from "./initialStore";
import { loadStore,saveStore } from "../lib/storage/localStore";
import type { Store } from "../../entities/meeting";

// Пользовательский React-хук: хранит данные в состоянии React и связывает их с локальным хранилищем.
// При запуске загружает сохранение, а после изменений store автоматически сохраняет новые данные.
// JSX не возвращает: отдаёт значения состояния и сеттер для использования в useAppController.

/**
 * Загружает сохранённое состояние и автоматически записывает его изменения в AsyncStorage.
 *
 * @returns Данные и функции хука; точная структура указана в сигнатуре TypeScript.
 */
export function usePersistentStore() {
  // useState возвращает [текущее значение, функцию его изменения].
  // Пока сохранение не загружено, используем initialStore — начальные данные приложения.
  // <Store> задаёт тип объекта. setStore обновляет состояние и вызывает повторный рендер.
  const [store, setStore] = useState<Store>(initialStore);
  // Завершилась ли попытка загрузки. true не означает успех: ошибка хранится отдельно.
  const [loaded, setLoaded] = useState(false);
  // Текст последней ошибки загрузки или сохранения; изначально ошибки нет.
  const [storageError, setStorageError] = useState("");
  // useEffect запускает загрузку после монтирования — добавления компонента в дерево React.
  // [] — пустой массив зависимостей: изменения состояния не перезапускают этот эффект.
  useEffect(() => {
    // Обычная переменная этого запуска эффекта, а не состояние React.
    // Показывает, можно ли ещё применять результат асинхронной загрузки.
    let active = true;
    // loadStore возвращает Promise: результат чтения станет доступен позже.
    loadStore()
      .then((saved) => {
        // then выполняется при успешном чтении. Если сохранение найдено и эффект ещё активен,
        // заменяем начальные данные сохранёнными. Если saved === null, оставляем initialStore.
        if (active && saved) setStore(saved);
      })
      .catch(() => {
        // catch обрабатывает ошибку чтения или восстановления данных.
        if (active) setStorageError("Не удалось загрузить сохранённые данные");
      })
      .finally(() => {
        // finally выполняется и после успеха, и после ошибки: ожидание загрузки закончено.
        if (active) setLoaded(true);
      });
    // Очистка эффекта: при размонтировании запрещаем применять запоздавший результат.
    return () => {
      active = false;
    };
  }, []);
  // Второй эффект отвечает за сохранение. Он выполняется после первого рендера,
  // затем повторяется при изменении store или loaded — значений из массива зависимостей.
  useEffect(() => {
    // До окончания загрузки не сохраняем initialStore поверх существующего сохранения.
    // После загрузки сохраняем текущее состояние; при ошибке чтения это будут начальные данные.
    if (loaded)
      saveStore(store).catch(() =>
        setStorageError("Не удалось сохранить данные")
      );
  }, [store, loaded]);
  // useAppController получает данные, сеттер, признак окончания загрузки и текст ошибки.
  // Когда он вызывает setStore, React обновляет состояние, а эффект выше запускает сохранение.
  return { store, setStore, loaded, storageError };
}
