// useContext читает данные из контекста, useMemo запоминает результат вычисления.
import { useContext, useMemo } from "react";
import type { ThemeColors } from "./colors";
import { ThemeContext } from "./ThemeProvider";

// хук для получения текущей темы внутри компонента или другого хука.
/**
 * Читает тему ближайшего ThemeProvider; без провайдера возвращает светлую тему.
 *
 * @returns Данные и функции хука; точная структура указана в сигнатуре TypeScript.
 */
export function useTheme() {
  // Читаем тему из ближайшего ThemeProvider выше по дереву компонентов.
  // Возвращаем объект с dark и colors. Если провайдера нет — светлую тему
  // по умолчанию, указанную при создании ThemeContext.
  return useContext(ThemeContext);
}


// T — тип результата: TypeScript определит его по переданной функции.
/**
 * Создаёт стили из цветов темы и запоминает результат до изменения цветов или функции создания.
 *
 * @param createStyles - Функция, создающая стили из цветов темы.
 * @returns Данные и функции хука; точная структура указана в сигнатуре TypeScript.
 */
export function useThemedStyles<T>(
  // Принимаем функцию, которая получает цвета и возвращает готовые стили.
  createStyles: (colors: ThemeColors) => T,
): T {
  // Получаем только цвета из текущей темы.
  const { colors } = useTheme();
  // Вызываем createStyles(colors) и запоминаем полученные стили.
  // При следующих отрисовках useMemo обычно возвращает сохранённый результат.
  // Если изменилась ссылка на createStyles или colors, вычисляет стили заново.
  // Поэтому функция createStyles, объявленная вне компонента, позволяет
  // переиспользовать результат; новая функция внутри компонента меняет ссылку
  // при каждой его отрисовке и приводит к повторному вычислению.
  return useMemo(() => createStyles(colors), [createStyles, colors]);
}
