import type { AppController } from "../src/app/model/useAppController";
import type { Store } from "../src/entities/meeting";
import { restaurants } from "../src/entities/meeting";
import { initialStore } from "../src/app/model/initialStore";

/** Новый независимый набор данных и обработчиков для каждого теста. */
export function makeController(overrides: Partial<AppController> = {}): AppController {
  const store = JSON.parse(JSON.stringify(initialStore)) as Store;
  return {
    removeParticipant: jest.fn(),
    sharePlaceInChat: jest.fn(),
    saveMeeting: jest.fn(),
    toggleMessageLike: jest.fn(),
    sendMessage: jest.fn(),
    enterSession: jest.fn(),
    confirmCurrentBooking: jest.fn(),
    selectLeader: jest.fn(),
    saveProfile: jest.fn(),
    inviteParticipant: jest.fn(),
    signOut: jest.fn(),
    fontsLoaded: true,
    fontError: null,
    store: store,
    loaded: true,
    screen: "meetings",
    setScreen: jest.fn(),
    selected: store.meetings[0].id,
    dialog: null,
    setDialog: jest.fn(),
    booking: restaurants[0],
    meetingSection: "active",
    setMeetingSection: jest.fn(),
    search: "",
    setSearch: jest.fn(),
    inviteName: "",
    setInviteName: jest.fn(),
    editName: store.name,
    setEditName: jest.fn(),
    editEmail: store.email,
    setEditEmail: jest.fn(),
    toast: null,
    showToast: jest.fn(),
    dismissToast: jest.fn(),
    cancelCurrentBooking: jest.fn(),
    filterBudget: "Все",
    setFilterBudget: jest.fn(),
    filterCuisine: "Все",
    setFilterCuisine: jest.fn(),
    filterDistance: "Все",
    setFilterDistance: jest.fn(),
    meeting: store.meetings[0],
    update: jest.fn(),
    updateMeeting: jest.fn(),
    addMessage: jest.fn(),
    leader: jest.fn(() => restaurants[0]),
    matchingMeetings: store.meetings,
    openMeeting: jest.fn(),
    book: jest.fn(),
    share: jest.fn(),
    vote: jest.fn(),
    pickAttachment: jest.fn(async () => {}),
    pickAvatar: jest.fn(async () => {}),
    goBack: jest.fn(),
    isTabs: true,
    title: "",
    ...overrides,
  };
}
